class LLMError(Exception):
    """Base exception for LLM provider errors."""

    def __init__(self, message: str, code: str = "llm_error"):
        super().__init__(message)
        self.code = code
        self.message = message


class LLMUnavailableError(LLMError):
    def __init__(self, message: str = "The language model is temporarily unavailable. Please try again."):
        super().__init__(message=message, code="llm_unavailable")


class LLMTimeoutError(LLMError):
    def __init__(self, message: str = "The language model request timed out. Please try again."):
        super().__init__(message=message, code="llm_timeout")


class LLMAuthenticationError(LLMError):
    def __init__(self, message: str = "Language model authentication failed. Please verify API credentials."):
        super().__init__(message=message, code="llm_auth_error")


class LLMClient(abc.ABC):
    """Abstract interface for streaming language model clients."""

    @abc.abstractmethod
    async def stream(self, messages: List[Dict[str, str]]) -> AsyncIterator[str]:
        """Yield text delta tokens as they are generated by the model."""
        pass

    async def generate(self, messages: List[Dict[str, str]]) -> str:
        """Non-streaming convenience helper collecting full text."""
        parts = []
        async for token in self.stream(messages):
            parts.append(token)
        return "".join(parts)


