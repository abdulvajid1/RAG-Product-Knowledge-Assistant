class OpenAICompatibleClient(LLMClient):
    """
    OpenAI-compatible client supporting OpenRouter, official OpenAI, and local LLM servers.
    Includes timeouts, bounded retries on transient errors, and SSE token streaming.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
        model: Optional[str] = None,
        timeout_seconds: Optional[int] = None,
        is_openrouter: bool = False,
    ):
        settings = get_settings()
        self.api_key = api_key if api_key is not None else settings.llm_api_key
        self.base_url = (base_url or settings.llm_base_url or "https://openrouter.ai/api/v1").rstrip("/")
        self.model = model or settings.llm_model or "google/gemini-2.0-flash-exp:free"
        self.timeout = float(timeout_seconds or settings.llm_timeout_seconds)
        self.is_openrouter = is_openrouter or "openrouter" in self.base_url.lower()

    async def stream(self, messages: List[Dict[str, str]]) -> AsyncIterator[str]:
        if not self.api_key:
            raise LLMAuthenticationError("No LLM API key provided. Set LLM_API_KEY in .env or environment.")

        endpoint = f"{self.base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        if self.is_openrouter:
            headers["HTTP-Referer"] = "https://filumart.internal"
            headers["X-Title"] = "Filumart Product Knowledge Assistant"

        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": 0.1,  # Low temperature per Spec 8.1
            "stream": True,
        }

        max_retries = 2
        last_exception = None

        for attempt in range(max_retries + 1):
            try:
                timeout_config = httpx.Timeout(self.timeout, connect=10.0)
                async with httpx.AsyncClient(timeout=timeout_config) as client:
                    async with client.stream("POST", endpoint, headers=headers, json=payload) as response:
                        if response.status_code == 401 or response.status_code == 403:
                            body = await response.aread()
                            logger.error(f"LLM authentication failed (status {response.status_code}): {body.decode()}")
                            raise LLMAuthenticationError("Authentication with the LLM provider failed. Check LLM_API_KEY.")
                        elif response.status_code in [429, 500, 502, 503, 504]:
                            body = await response.aread()
                            logger.warning(
                                f"Transient LLM provider error (attempt {attempt + 1}/{max_retries + 1}): "
                                f"{response.status_code} - {body.decode()[:200]}"
                            )
                            if attempt < max_retries:
                                await asyncio.sleep(1.0 * (2 ** attempt))
                                continue
                            raise LLMUnavailableError(f"LLM provider returned status {response.status_code}.")
                        elif response.status_code != 200:
                            body = await response.aread()
                            logger.error(f"Unexpected LLM response {response.status_code}: {body.decode()}")
                            raise LLMError(f"LLM provider error (status {response.status_code})")

                        # Process SSE stream from LLM
                        async for line in response.aiter_lines():
                            line = line.strip()
                            if not line:
                                continue
                            if line.startswith("data: "):
                                data_str = line[6:].strip()
                                if data_str == "[DONE]":
                                    break
                                try:
                                    data_json = json.loads(data_str)
                                    choices = data_json.get("choices", [])
                                    if choices:
                                        delta = choices[0].get("delta", {})
                                        content = delta.get("content")
                                        if content:
                                            yield content
                                except json.JSONDecodeError:
                                    continue
                        return

            except httpx.TimeoutException as e:
                logger.warning(f"LLM request timed out (attempt {attempt + 1}): {e}")
                last_exception = LLMTimeoutError()
                if attempt < max_retries:
                    await asyncio.sleep(1.0 * (2 ** attempt))
                    continue
                raise last_exception
            except (httpx.ConnectError, httpx.NetworkError) as e:
                logger.warning(f"LLM network error (attempt {attempt + 1}): {e}")
                last_exception = LLMUnavailableError()
                if attempt < max_retries:
                    await asyncio.sleep(1.0 * (2 ** attempt))
                    continue
                raise last_exception


def get_llm_client(force_mock: bool = False) -> LLMClient:
    """Factory creating configured LLM client instance."""
    settings = get_settings()

    if force_mock or settings.llm_provider.lower() == "mock":
        return MockLLM()

    if settings.llm_provider.lower() in ["openrouter", "openai"]:
        is_or = settings.llm_provider.lower() == "openrouter" or "openrouter" in settings.llm_base_url.lower()
        return OpenAICompatibleClient(
            api_key=settings.llm_api_key,
            base_url=settings.llm_base_url or ("https://openrouter.ai/api/v1" if is_or else None),
            model=settings.llm_model,
            timeout_seconds=settings.llm_timeout_seconds,
            is_openrouter=is_or,
        )

    # Fallback to MockLLM if unrecognized
    logger.warning(f"Unknown LLM provider '{settings.llm_provider}'. Defaulting to MockLLM.")
    return MockLLM()
